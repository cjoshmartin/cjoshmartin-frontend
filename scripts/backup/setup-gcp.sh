#!/usr/bin/env bash
# Provisions the private backup bucket and keyless GitHub Actions access for
# the weekly Sanity backup (docs/sanity-migration-plan.md §10):
#
#   - bucket gs://cjoshmartin-sanity-backups: us-central1, Standard storage,
#     uniform bucket-level access, public access prevention enforced
#   - service account sanity-backup with roles/storage.objectCreator and
#     roles/storage.objectViewer on that bucket only (no delete permission)
#   - Workload Identity pool + GitHub OIDC provider that only admits
#     cjoshmartin/cjoshmartin-frontend (repository id 737918690) on refs/heads/main
#   - roles/iam.workloadIdentityUser for that repository on the service account
#
# Then prints the gh commands that set the GitHub variables and secrets.
#
# Safe to run more than once: existing resources are checked and brought to
# the desired settings instead of being created again. It never deletes
# anything. Run it after `gcloud auth login` as an owner of com-cjoshmartin.
#
# Usage: scripts/backup/setup-gcp.sh [--print-only]
#   --print-only   Print every command without running anything (no gcloud
#                  calls at all). The output is a runnable script.
set -euo pipefail

readonly PROJECT_ID="com-cjoshmartin"
readonly REGION="us-central1"
readonly BUCKET="cjoshmartin-sanity-backups"
readonly SA_NAME="sanity-backup"
readonly SA_EMAIL="${SA_NAME}@${PROJECT_ID}.iam.gserviceaccount.com"
readonly POOL_ID="github-actions"
readonly PROVIDER_ID="cjoshmartin-frontend"
# The repository's canonical name. It moved from the cjoshmartin-com
# organization to the cjoshmartin user account; the old name only redirects,
# and GitHub's OIDC token carries the canonical owner/name, so the provider
# condition and the principalSet must use this one.
readonly GITHUB_REPO="cjoshmartin/cjoshmartin-frontend"
# The numeric id survives renames and cannot be reused by a new repository
# with the same name, so the provider checks it as well as the name.
readonly GITHUB_REPO_ID="737918690"
readonly GITHUB_REF="refs/heads/main"
readonly SANITY_PROJECT_ID="j3vdh6ti"
readonly ATTRIBUTE_MAPPING="google.subject=assertion.sub,attribute.repository=assertion.repository,attribute.repository_id=assertion.repository_id,attribute.ref=assertion.ref"
readonly ATTRIBUTE_CONDITION="assertion.repository == '${GITHUB_REPO}' && assertion.repository_id == '${GITHUB_REPO_ID}' && assertion.ref == '${GITHUB_REF}'"
# Plain arrays (no readonly array literals) to stay compatible with the bash 3.2
# that macOS ships.
BUCKET_ROLES=("roles/storage.objectCreator" "roles/storage.objectViewer")
REQUIRED_APIS=("iam.googleapis.com" "iamcredentials.googleapis.com" "sts.googleapis.com" "storage.googleapis.com")

PRINT_ONLY=false

usage() {
  sed -n '2,21p' "$0" | sed 's/^# \{0,1\}//'
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --print-only) PRINT_ONLY=true ;;
    -h | --help)
      usage
      exit 0
      ;;
    *)
      echo "Unknown argument: $1" >&2
      usage >&2
      exit 2
      ;;
  esac
  shift
done

# In --print-only mode the project number is not looked up, so commands that
# need it show a ${PROJECT_NUMBER} shell variable instead (set by the first
# printed line). shell_quote keeps such arguments in double quotes so the
# printed script expands it.
# shellcheck disable=SC2016 # the literal ${PROJECT_NUMBER} is intended
readonly PROJECT_NUMBER_REF='${PROJECT_NUMBER}'

shell_quote() {
  local value=$1
  local double_quote_unsafe='[$`"\\!]'
  if [[ $value =~ ^[A-Za-z0-9_./:=@,+-]+$ ]]; then
    printf '%s' "$value"
  elif [[ $value == *"$PROJECT_NUMBER_REF"* ]]; then
    # Escape what is special inside double quotes, except the $ of ${PROJECT_NUMBER}.
    printf '"%s"' "$(printf '%s' "$value" | sed 's/[\\"`]/\\&/g')"
  elif [[ $value != *"'"* ]]; then
    printf "'%s'" "$value"
  elif ! [[ $value =~ $double_quote_unsafe ]]; then
    printf '"%s"' "$value"
  else
    printf "'%s'" "$(printf '%s' "$value" | sed "s/'/'\\\\''/g")"
  fi
}

print_command() {
  local line="" arg
  for arg in "$@"; do
    line+=" $(shell_quote "$arg")"
  done
  printf '%s\n' "${line# }"
}

# Prints a command, then runs it unless --print-only.
run() {
  print_command "$@"
  if [[ $PRINT_ONLY == false ]]; then
    "$@"
  fi
}

note() {
  printf '\n# %s\n' "$*"
}

# Read-only probe used for idempotency; never called in --print-only mode.
succeeds() {
  "$@" >/dev/null 2>&1
}

if [[ $PRINT_ONLY == true ]]; then
  echo "#!/usr/bin/env bash"
  echo "# Generated by scripts/backup/setup-gcp.sh --print-only. A real run checks each"
  echo "# resource first, skips what already exists, and updates settings that differ."
  echo "set -euo pipefail"
  # shellcheck disable=SC2016 # printed for the generated script, not expanded here
  printf '%s\n' 'PROJECT_NUMBER="$(gcloud projects describe com-cjoshmartin --format='"'"'value(projectNumber)'"'"')"'
  PROJECT_NUMBER=$PROJECT_NUMBER_REF
else
  command -v gcloud >/dev/null || {
    echo "gcloud is not installed" >&2
    exit 1
  }
  ACCOUNT=$(gcloud auth list --filter=status:ACTIVE --format='value(account)')
  echo "# gcloud account: ${ACCOUNT:-none}"
  if [[ -z $ACCOUNT ]]; then
    echo "Run 'gcloud auth login' as an owner of ${PROJECT_ID} first." >&2
    exit 1
  fi
  PROJECT_NUMBER=$(gcloud projects describe "$PROJECT_ID" --format='value(projectNumber)')
  echo "# ${PROJECT_ID} has project number ${PROJECT_NUMBER}"
fi
readonly PROJECT_NUMBER
readonly POOL_NAME="projects/${PROJECT_NUMBER}/locations/global/workloadIdentityPools/${POOL_ID}"
readonly PROVIDER_NAME="${POOL_NAME}/providers/${PROVIDER_ID}"
readonly PRINCIPAL_SET="principalSet://iam.googleapis.com/${POOL_NAME}/attribute.repository/${GITHUB_REPO}"

note "APIs needed for Workload Identity Federation and Cloud Storage"
run gcloud services enable "${REQUIRED_APIS[@]}" --project="$PROJECT_ID"

note "Bucket gs://${BUCKET}"
if [[ $PRINT_ONLY == false ]] && succeeds gcloud storage buckets describe "gs://${BUCKET}" --project="$PROJECT_ID"; then
  read -r location storage_class < <(gcloud storage buckets describe "gs://${BUCKET}" --format='value(location,default_storage_class)')
  location_upper=$(printf '%s' "$location" | tr '[:lower:]' '[:upper:]')
  region_upper=$(printf '%s' "$REGION" | tr '[:lower:]' '[:upper:]')
  class_upper=$(printf '%s' "$storage_class" | tr '[:lower:]' '[:upper:]')
  if [[ $location_upper != "$region_upper" || $class_upper != "STANDARD" ]]; then
    echo "gs://${BUCKET} exists in ${location} with class ${storage_class}; expected ${REGION} STANDARD. Fix it by hand; this script will not recreate a bucket." >&2
    exit 1
  fi
  echo "# exists (${location}, ${storage_class}); enforcing access settings"
  run gcloud storage buckets update "gs://${BUCKET}" --uniform-bucket-level-access --public-access-prevention
else
  run gcloud storage buckets create "gs://${BUCKET}" --project="$PROJECT_ID" --location="$REGION" \
    --default-storage-class=STANDARD --uniform-bucket-level-access --public-access-prevention
fi

note "Service account ${SA_EMAIL}"
if [[ $PRINT_ONLY == false ]] && succeeds gcloud iam service-accounts describe "$SA_EMAIL" --project="$PROJECT_ID"; then
  echo "# exists"
else
  run gcloud iam service-accounts create "$SA_NAME" --project="$PROJECT_ID" \
    --display-name="Sanity backup (GitHub Actions)" \
    --description="Writes weekly Sanity backups to gs://${BUCKET}. Create and read only; no delete."
fi

note "Bucket roles for the service account: create and read objects, nothing else"
for role in "${BUCKET_ROLES[@]}"; do
  run gcloud storage buckets add-iam-policy-binding "gs://${BUCKET}" \
    --member="serviceAccount:${SA_EMAIL}" --role="$role"
done
if [[ $PRINT_ONLY == false ]]; then
  granted=$(gcloud storage buckets get-iam-policy "gs://${BUCKET}" --flatten='bindings[].members' \
    --filter="bindings.members:serviceAccount:${SA_EMAIL}" --format='value(bindings.role)' | sort | tr '\n' ' ')
  expected=$(printf '%s\n' "${BUCKET_ROLES[@]}" | sort | tr '\n' ' ')
  if [[ $granted != "$expected" ]]; then
    echo "The service account has these roles on gs://${BUCKET}: ${granted}; expected exactly: ${expected}. Remove the extra roles by hand." >&2
    exit 1
  fi
  echo "# verified: ${granted}"
fi

note "Workload Identity pool ${POOL_ID}"
pool_state=""
if [[ $PRINT_ONLY == false ]]; then
  pool_state=$(gcloud iam workload-identity-pools describe "$POOL_ID" --project="$PROJECT_ID" --location=global --format='value(state)' 2>/dev/null || true)
fi
case "$pool_state" in
  ACTIVE) echo "# exists" ;;
  DELETED) run gcloud iam workload-identity-pools undelete "$POOL_ID" --project="$PROJECT_ID" --location=global ;;
  *)
    run gcloud iam workload-identity-pools create "$POOL_ID" --project="$PROJECT_ID" --location=global \
      --display-name="GitHub Actions"
    ;;
esac

note "GitHub OIDC provider ${PROVIDER_ID}: only ${GITHUB_REPO} on ${GITHUB_REF}"
provider_state=""
if [[ $PRINT_ONLY == false ]]; then
  provider_state=$(gcloud iam workload-identity-pools providers describe "$PROVIDER_ID" --project="$PROJECT_ID" \
    --location=global --workload-identity-pool="$POOL_ID" --format='value(state)' 2>/dev/null || true)
fi
case "$provider_state" in
  ACTIVE | DELETED)
    if [[ $provider_state == DELETED ]]; then
      run gcloud iam workload-identity-pools providers undelete "$PROVIDER_ID" --project="$PROJECT_ID" \
        --location=global --workload-identity-pool="$POOL_ID"
    fi
    run gcloud iam workload-identity-pools providers update-oidc "$PROVIDER_ID" --project="$PROJECT_ID" \
      --location=global --workload-identity-pool="$POOL_ID" \
      --issuer-uri="https://token.actions.githubusercontent.com" \
      --attribute-mapping="$ATTRIBUTE_MAPPING" --attribute-condition="$ATTRIBUTE_CONDITION"
    ;;
  *)
    run gcloud iam workload-identity-pools providers create-oidc "$PROVIDER_ID" --project="$PROJECT_ID" \
      --location=global --workload-identity-pool="$POOL_ID" --display-name="cjoshmartin-frontend main" \
      --issuer-uri="https://token.actions.githubusercontent.com" \
      --attribute-mapping="$ATTRIBUTE_MAPPING" --attribute-condition="$ATTRIBUTE_CONDITION"
    ;;
esac

note "Let ${GITHUB_REPO} impersonate the service account"
run gcloud iam service-accounts add-iam-policy-binding "$SA_EMAIL" --project="$PROJECT_ID" \
  --role=roles/iam.workloadIdentityUser --member="$PRINCIPAL_SET"

note "GitHub configuration. Variables are not secret. Secrets are read from secrets.env and piped on stdin, so they never appear in shell history or the process list."
print_command gh variable set GCP_WORKLOAD_IDENTITY_PROVIDER --repo "$GITHUB_REPO" --body "$PROVIDER_NAME"
print_command gh variable set GCP_BACKUP_SERVICE_ACCOUNT --repo "$GITHUB_REPO" --body "$SA_EMAIL"
print_command gh variable set BACKUP_BUCKET --repo "$GITHUB_REPO" --body "$BUCKET"
print_command gh variable set SANITY_PROJECT_ID --repo "$GITHUB_REPO" --body "$SANITY_PROJECT_ID"
# The only secret is the Viewer token, stored as SANITY_BACKUP_TOKEN. Videos are
# Sanity file assets now, so the backup needs no Mux token.
printf '(set -a; . ~/cjoshmartin-migration/secrets.env; set +a; printf %%s "$%s" | gh secret set %s --repo %s)\n' \
  SANITY_READ_TOKEN SANITY_BACKUP_TOKEN "$GITHUB_REPO"

if [[ $PRINT_ONLY == true ]]; then
  echo
  echo "# --print-only: nothing was run."
else
  echo
  echo "# Done. Run the gh commands above, then start the workflow from the Actions tab."
fi
